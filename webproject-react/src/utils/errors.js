// Повідомлення користувачеві за видом відмови. Без звернень до DOM: стан мережі передається параметром.
// Повертає { title, advice } — що сталося і що робити.
export function describeError(error, { online = true } = {}) {
  if (!online) {
    return { title: "Немає з'єднання з мережею.", advice: 'Перевірте підключення до інтернету й натисніть «Спробувати ще раз».' };
  }
  const status = error?.status;
  if (status === 404) return { title: 'Дані не знайдено.', advice: 'Можливо, адреса ресурсу змінилася. Спробуйте пізніше.' };
  if (status === 401) return { title: 'Потрібно ввійти.', advice: 'Увійдіть до облікового запису й повторіть дію.' };
  if (status === 403) return { title: 'Немає доступу.', advice: 'Ця дія недоступна для вашого облікового запису.' };
  if (status === 429) return { title: 'Забагато запитів.', advice: 'Сервер тимчасово обмежив кількість запитів — зачекайте хвилину.' };
  if (status >= 500) return { title: 'Сервер тимчасово недоступний.', advice: 'Спробуйте пізніше.' };
  if (status >= 400) return { title: 'Сервер не зміг обробити запит.', advice: 'Спробуйте змінити запит або повторіть пізніше.' };
  // fetch відхилився без відповіді, хоча мережа є: сервер не відповідає або запит заблоковано (CORS)
  if (error?.name === 'TypeError') {
    return { title: "Не вдалося зв'язатися із сервером каталогу.", advice: 'Сервер не відповідає. Спробуйте трохи пізніше.' };
  }
  return { title: 'Сталася непередбачена помилка.', advice: 'Оновіть сторінку або спробуйте пізніше.' };
}
